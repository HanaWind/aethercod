export const translate = (language: Language, value: string) =>
  language === "en" ? text[value] ?? value : value;

export function displayTypeName(language: Language, type: EntityType) {
  return language === "en" && type.is_builtin ? builtInTypes[type.id] ?? type.name : type.name;
}

export function displayFieldName(language: Language, field: FieldDefinition) {
  return language === "en" && field.protected ? builtInFields[field.name] ?? field.name : field.name;
}

export function displayFieldValue(language: Language, field: FieldDefinition, value: unknown) {
  if (language !== "en" || !field.protected || typeof value !== "string") return value;
  return builtInFields[value] ?? value;
}

export function displayTypeOption(language: Language, typeId: string, value: string) {
  return language === "en" && typeId === "place" ? builtInFields[value] ?? value : value;
}
